#!/usr/bin/env bash
# create_conda_env.sh — create/update the isolated Python environment used by
# @task.external_python and mounted read-only into every task pod.
#
# Usage: sudo -E scripts/create_conda_env.sh [--recreate]
#
# Source of truth: envs/<env>/environment.yml (direct dependencies, pinned).
#   1) New environment: built from environment.lock.yml when it exists (every
#      package at the exact committed version), else from environment.yml.
#   2) environment.yml is applied on top, so edits to it (new/upgraded
#      libraries) are installed. When nothing changed this is a no-op.
#   3) The final state is exported back to environment.lock.yml -> commit it.
#
# The YAML files are read here and installed with `conda create/install
# --override-channels -c conda-forge` + `pip install`, NOT with `conda env
# create -f`: that command has no --override-channels, so on Miniconda it also
# pulls Anaconda's 'defaults' channel and stops on its terms of service
# (CondaToSNonInteractiveError).
set -euo pipefail
# shellcheck source=lib/common.sh
. "$(dirname "$0")/lib/common.sh"

load_env
require_vars CONDA_HOME CONDA_ENVS_HOST_PATH PYTHON_ENV_NAME

RECREATE=0
[ "${1:-}" = "--recreate" ] && RECREATE=1

ENV_PATH="$CONDA_ENVS_HOST_PATH/$PYTHON_ENV_NAME"
ENV_DIR="$REPO_ROOT/envs/$PYTHON_ENV_NAME"
ENV_FILE_YML="$ENV_DIR/environment.yml"
LOCK_FILE="$ENV_DIR/environment.lock.yml"
CONDA="$CONDA_HOME/bin/conda"
PY="$ENV_PATH/bin/python"

[ -f "$ENV_FILE_YML" ] || die "No existe $ENV_FILE_YML (definición del entorno)."

if [ ! -x "$CONDA" ]; then
    info "Instalando Miniconda en $CONDA_HOME"
    require_cmd curl
    case "$(uname -m)" in
        x86_64)  MC_ARCH=x86_64 ;;
        aarch64) MC_ARCH=aarch64 ;;
        *) die "Arquitectura no soportada: $(uname -m)" ;;
    esac
    TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
    curl -fsSL "https://repo.anaconda.com/miniconda/Miniconda3-latest-Linux-${MC_ARCH}.sh" -o "$TMP/mc.sh"
    bash "$TMP/mc.sh" -b -p "$CONDA_HOME"
fi

# specs <file> <conda|pip> — the package specs of an environment YAML file:
# "  - name=version" entries (conda) or the "      - name==version" entries
# under "  - pip:" (pip). Comments and blank lines are ignored.
specs() {
    awk -v kind="$2" '
        /^dependencies:/        { deps = 1; next }
        !deps                   { next }
        /^  - pip:[[:space:]]*$/ { pip = 1; next }
        /^  - / && !pip         { if (kind == "conda") { sub(/^  - /, ""); print } next }
        /^      - / && pip      { if (kind == "pip")   { sub(/^      - /, ""); print } }
    ' "$1"
}

# install_from <file> — install its conda specs, then its pip specs, into ENV_PATH.
install_from() {
    local file="$1" conda_specs pip_specs
    mapfile -t conda_specs < <(specs "$file" conda)
    [ "${#conda_specs[@]}" -gt 0 ] || die "$file no declara paquetes conda (al menos python y pip)"
    if [ -d "$ENV_PATH" ]; then
        # Install what the file asks for WITHOUT moving anything else: --freeze-installed,
        # and an empty aggressive_update_packages (by default conda ALWAYS upgrades
        # ca-certificates/certifi/openssl on any install, so a fresh env drifted from the lock).
        CONDA_AGGRESSIVE_UPDATE_PACKAGES="" \
            "$CONDA" install -y -p "$ENV_PATH" --override-channels -c conda-forge --freeze-installed \
            "${conda_specs[@]}"
    else
        mkdir -p "$CONDA_ENVS_HOST_PATH"
        "$CONDA" create -y -p "$ENV_PATH" --override-channels -c conda-forge "${conda_specs[@]}"
    fi
    pip_specs="$(mktemp)"
    specs "$file" pip > "$pip_specs"
    if [ -s "$pip_specs" ]; then
        "$PY" -m pip install --no-cache-dir -r "$pip_specs"
    fi
    rm -f "$pip_specs"
}

if [ -d "$ENV_PATH" ] && [ "$RECREATE" -eq 1 ]; then
    warn "Eliminando entorno existente $ENV_PATH"
    # Not `conda env remove`: like `conda env create`, it consults Anaconda's 'defaults'
    # channel and stops on its terms of service (CondaToSNonInteractiveError). A prefix
    # environment is just a directory.
    rm -rf "$ENV_PATH"
fi

if [ ! -d "$ENV_PATH" ]; then
    SOURCE="$ENV_FILE_YML"
    [ -f "$LOCK_FILE" ] && SOURCE="$LOCK_FILE"
    info "Paso 1/3: creando $ENV_PATH desde $(basename "$SOURCE")"
    install_from "$SOURCE"
else
    info "Paso 1/3: el entorno ya existe ($ENV_PATH)"
fi

info "Paso 2/3: aplicando $(basename "$ENV_FILE_YML") (instala lo nuevo o cambiado)"
install_from "$ENV_FILE_YML"

# Task pods run as UID 50000: the environment must be world-readable/executable.
chmod -R a+rX "$ENV_PATH"

"$PY" -m pip check || warn "pip check reporta inconsistencias (revisar arriba)"
"$PY" --version
"$PY" -c "import airflow, polars, pyarrow; print('airflow', airflow.__version__, '| polars', polars.__version__)"

info "Paso 3/3: exportando el lock"
{
    echo "# AUTO-GENERATED by scripts/create_conda_env.sh — do not edit; edit environment.yml."
    # nodefaults: never pull from Anaconda's 'defaults' channel (terms of service),
    # even on hosts whose .condarc lists it (e.g. Miniconda).
    "$CONDA" env export -p "$ENV_PATH" --no-builds \
        | sed -e '/^prefix:/d' -e '/^  - nodefaults$/d' -e '/^  - defaults$/d' -e "s/^name: .*/name: $PYTHON_ENV_NAME/" \
        | awk '{ print } /^channels:/ { print "  - nodefaults" }'
} > "$LOCK_FILE.tmp"
mv "$LOCK_FILE.tmp" "$LOCK_FILE"
ok "Entorno listo: $ENV_PATH  (lock: envs/$PYTHON_ENV_NAME/environment.lock.yml -> commitéalo)"
